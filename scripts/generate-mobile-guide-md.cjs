#!/usr/bin/env node
// scripts/generate-mobile-guide-md.cjs
//
// Regenerate docs/mobile-setup-guide.md from the typed source of truth
// in constants/mobileSetupGuideContent.ts. The modal in the Settings
// panel and the markdown mirror on GitHub both render from the same
// data, so contributors only need to edit the .ts file — this script
// keeps the markdown in sync.
//
// Run:
//     node scripts/generate-mobile-guide-md.cjs
//
// Implementation: we transpile the TS file on the fly via
// `typescript.transpileModule` (TS is already a devDep), require the
// resulting CJS, then walk the structured data and emit markdown. No
// dependency on ts-node / esbuild.

'use strict';

const fs = require('fs');
const path = require('path');
const Module = require('module');
const ts = require('typescript');

const projectRoot = path.resolve(__dirname, '..');
const sourcePath = path.join(projectRoot, 'constants', 'mobileSetupGuideContent.ts');
const outPath = path.join(projectRoot, 'docs', 'mobile-setup-guide.md');

function transpileTsToCjs(source) {
  const result = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
      esModuleInterop: true,
      allowSyntheticDefaultImports: true,
      isolatedModules: true,
      strict: false,
    },
  });
  return result.outputText;
}

// Run the transpiled CJS in an isolated Module, short-circuiting any
// `import type` / runtime imports that don't actually exist at build
// time. Since mobileSetupGuideContent.ts only imports a type (`Language`)
// and that's erased by TS, the compiled JS has no real require() calls.
function loadModuleContent() {
  const raw = fs.readFileSync(sourcePath, 'utf8');
  const compiled = transpileTsToCjs(raw);
  const syntheticPath = path.join(path.dirname(sourcePath), 'mobileSetupGuideContent.generated.cjs');

  const m = new Module(syntheticPath, module);
  m.filename = syntheticPath;
  m.paths = Module._nodeModulePaths(path.dirname(syntheticPath));
  m._compile(compiled, syntheticPath);
  return m.exports;
}

function escapeMd(text) {
  return String(text || '').replace(/\*/g, '\\*');
}

function renderStep(step, index) {
  const out = [];
  out.push(`${index}. ${escapeMd(step.text)}`);
  if (step.note) {
    out.push(`   > ${escapeMd(step.note)}`);
  }
  if (step.link) {
    out.push(`   - [${escapeMd(step.link.label)}](${step.link.url})`);
  }
  return out.join('\n');
}

function renderError(err) {
  const out = [];
  out.push(`### \`${err.code}\``);
  out.push('');
  out.push(`**现象 / Symptom**: ${escapeMd(err.symptom)}`);
  out.push('');
  out.push(`**原因 / Cause**: ${escapeMd(err.cause)}`);
  out.push('');
  out.push('**修复 / Fix**:');
  err.fixSteps.forEach((fix, i) => {
    out.push(`${i + 1}. ${escapeMd(fix)}`);
  });
  if (err.actionLink) {
    out.push('');
    out.push(`➜ [${escapeMd(err.actionLink.label)}](${err.actionLink.url})`);
  }
  return out.join('\n');
}

function renderSection(section, language) {
  const out = [];
  out.push(`## ${section.title}`);
  out.push('');
  out.push(section.intro);
  out.push('');
  if (section.steps && section.steps.length > 0) {
    section.steps.forEach((step, i) => {
      out.push(renderStep(step, i + 1));
      out.push('');
    });
  }
  if (section.errors && section.errors.length > 0) {
    section.errors.forEach((err) => {
      out.push(renderError(err));
      out.push('');
    });
  }
  if (section.tailNote) {
    out.push(`> **${language === 'zh' ? '小结' : 'Summary'}**: ${section.tailNote}`);
    out.push('');
  }
  return out.join('\n');
}

function renderMarkdown(mod) {
  const sectionsZh = mod.MOBILE_SETUP_GUIDE.zh;
  const sectionsEn = mod.MOBILE_SETUP_GUIDE.en;

  const header = [
    '# 手机远程访问 · 配置教程 / Mobile Remote Access Setup Guide',
    '',
    '> **AUTOGENERATED**: 这份文档由 `scripts/generate-mobile-guide-md.cjs` 从 `constants/mobileSetupGuideContent.ts` 生成。',
    '> 请修改 `.ts` 源文件后运行 `node scripts/generate-mobile-guide-md.cjs` 再重新提交，不要直接编辑本文件。',
    '',
    '> **AUTOGENERATED**: This document is generated by `scripts/generate-mobile-guide-md.cjs` from `constants/mobileSetupGuideContent.ts`.',
    '> Edit the `.ts` source file and re-run `node scripts/generate-mobile-guide-md.cjs`. Do NOT edit this file directly.',
    '',
    '---',
    '',
    '目录 / Table of Contents:',
    '',
    '- [中文教程](#中文教程)',
    '- [English guide](#english-guide)',
    '',
  ].join('\n');

  const zhPart = [
    '---',
    '',
    '## 中文教程',
    '',
    sectionsZh.map((s) => renderSection(s, 'zh')).join('\n'),
  ].join('\n');

  const enPart = [
    '---',
    '',
    '## English Guide',
    '',
    sectionsEn.map((s) => renderSection(s, 'en')).join('\n'),
  ].join('\n');

  return [header, zhPart, enPart].join('\n');
}

function main() {
  const mod = loadModuleContent();
  const md = renderMarkdown(mod);
  const docsDir = path.dirname(outPath);
  if (!fs.existsSync(docsDir)) fs.mkdirSync(docsDir, { recursive: true });
  fs.writeFileSync(outPath, md, 'utf8');
  const rel = path.relative(projectRoot, outPath);
  console.log(`✓ Wrote ${rel} (${md.length} chars)`);
}

try {
  main();
} catch (e) {
  console.error('✗ Failed to regenerate mobile setup guide markdown:');
  console.error(e && e.stack ? e.stack : e);
  process.exit(1);
}
